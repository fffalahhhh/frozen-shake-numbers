-- Frozen Shake Cash Tracker: initial schema.
-- Every financial table is tenant-scoped by shop_id. Composite foreign keys
-- (shop_id, category_id) / (shop_id, partner_id) make it impossible at the DB
-- level for a record to reference another shop's category or partner.

CREATE TABLE users (
    id              uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    email           text NOT NULL,
    name            text NOT NULL DEFAULT '',
    password_hash   text NOT NULL,
    default_shop_id uuid,
    created_at      timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX users_email_key ON users (lower(email));

CREATE TABLE sessions (
    token_hash bytea PRIMARY KEY,
    user_id    uuid NOT NULL REFERENCES users ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL
);
CREATE INDEX sessions_user_idx ON sessions (user_id);

CREATE TABLE password_reset_tokens (
    token_hash bytea PRIMARY KEY,
    user_id    uuid NOT NULL REFERENCES users ON DELETE CASCADE,
    created_at timestamptz NOT NULL DEFAULT now(),
    expires_at timestamptz NOT NULL,
    used_at    timestamptz
);
CREATE INDEX password_reset_tokens_user_idx ON password_reset_tokens (user_id);

CREATE TABLE shops (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    name       text NOT NULL,
    address    text NOT NULL DEFAULT '',
    timezone   text NOT NULL DEFAULT 'Asia/Kolkata',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE users
    ADD CONSTRAINT users_default_shop_fk FOREIGN KEY (default_shop_id) REFERENCES shops ON DELETE SET NULL;

CREATE TABLE shop_members (
    shop_id    uuid NOT NULL REFERENCES shops ON DELETE CASCADE,
    user_id    uuid NOT NULL REFERENCES users ON DELETE CASCADE,
    role       text NOT NULL DEFAULT 'member' CHECK (role IN ('owner', 'member')),
    created_at timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (shop_id, user_id)
);
CREATE INDEX shop_members_user_idx ON shop_members (user_id);

CREATE TABLE expense_categories (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    shop_id    uuid NOT NULL REFERENCES shops ON DELETE CASCADE,
    name       text NOT NULL,
    is_default boolean NOT NULL DEFAULT false,
    active     boolean NOT NULL DEFAULT true,
    sort_order int NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (shop_id, id)
);
CREATE UNIQUE INDEX expense_categories_name_key ON expense_categories (shop_id, lower(name));

CREATE TABLE partners (
    id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    shop_id    uuid NOT NULL REFERENCES shops ON DELETE CASCADE,
    name       text NOT NULL,
    active     boolean NOT NULL DEFAULT true,
    sort_order int NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT now(),
    UNIQUE (shop_id, id)
);
CREATE UNIQUE INDEX partners_name_key ON partners (shop_id, lower(name));

-- One revenue total per shop per day.
CREATE TABLE daily_revenues (
    shop_id       uuid NOT NULL REFERENCES shops ON DELETE CASCADE,
    business_date date NOT NULL,
    amount        numeric(12, 2) NOT NULL CHECK (amount >= 0),
    updated_by    uuid REFERENCES users ON DELETE SET NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (shop_id, business_date)
);

-- ids may be generated by the client: they double as idempotency keys for
-- offline sync (INSERT ... ON CONFLICT (id) DO NOTHING).
CREATE TABLE expenses (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    shop_id       uuid NOT NULL REFERENCES shops ON DELETE CASCADE,
    business_date date NOT NULL,
    amount        numeric(12, 2) NOT NULL CHECK (amount > 0),
    category_id   uuid NOT NULL,
    category_name text NOT NULL, -- snapshot: survives renames/hiding
    note          text NOT NULL DEFAULT '',
    created_by    uuid REFERENCES users ON DELETE SET NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (shop_id, category_id) REFERENCES expense_categories (shop_id, id)
);
CREATE INDEX expenses_shop_date_idx ON expenses (shop_id, business_date);

CREATE TABLE partner_handovers (
    id            uuid PRIMARY KEY DEFAULT gen_random_uuid(),
    shop_id       uuid NOT NULL REFERENCES shops ON DELETE CASCADE,
    business_date date NOT NULL,
    amount        numeric(12, 2) NOT NULL CHECK (amount > 0),
    partner_id    uuid NOT NULL,
    partner_name  text NOT NULL, -- snapshot: survives renames/deactivation
    note          text NOT NULL DEFAULT '',
    created_by    uuid REFERENCES users ON DELETE SET NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    FOREIGN KEY (shop_id, partner_id) REFERENCES partners (shop_id, id)
);
CREATE INDEX partner_handovers_shop_date_idx ON partner_handovers (shop_id, business_date);
CREATE INDEX partner_handovers_partner_idx ON partner_handovers (shop_id, partner_id);
